// Helper functions
export function filterAccessories(
  items: FormworkAccessoryRecord[],
  query: string,
  category: string,
  status: string,
  material: string
): FormworkAccessoryRecord[] {
  return items.filter((item) => {
    const q = (query || "").toLowerCase();
    const matchesQuery =
      !q ||
      String(item.code || "").toLowerCase().includes(q) ||
      String(item.name || "").toLowerCase().includes(q) ||
      String(item.id || "").toLowerCase().includes(q) ||
      String(item.warehouseLocation || "").toLowerCase().includes(q) ||
      String(item.material || "").toLowerCase().includes(q) ||
      String(item.supplier || "").toLowerCase().includes(q);

    const matchesCategory = category === "All" || item.category === category;
    const matchesStatus = status === "All" || item.status === status;
    const matchesMaterial = material === "All" || item.material === material;

    return matchesQuery && matchesCategory && matchesStatus && matchesMaterial;
  });
}
